#!/usr/bin/env python
"""Push the fine-tuned model(s) and both 15K datasets to the Hugging Face Hub.

Needs a write token already stored by `huggingface-cli login` (never passed on the command line).
Usage (login node is fine: network + file IO only):
  python push_to_hub.py --namespace <user_or_org> --models random15k advanced15k --datasets random15k advanced15k [--private]

Model repos:   <namespace>/Qwen2.5-3B-Instruct-SFT-<run>
Dataset repos: <namespace>/acereason-<run>   (the 15K json in LLaMA-Factory alpaca format + its manifest)
"""
import argparse, json, os, sys
from huggingface_hub import HfApi, create_repo, upload_folder, upload_file

P = "/projects/ai_wireless_hu_lab/yuanzhou/reasoning_sft"
ap = argparse.ArgumentParser()
ap.add_argument("--namespace", default="yuan-zhou-hf")
ap.add_argument("--models", nargs="*", default=[])
ap.add_argument("--datasets", nargs="*", default=[])
ap.add_argument("--private", action="store_true")
ap.add_argument("--dry-run", action="store_true")
a = ap.parse_args()
api = HfApi()
who = api.whoami()["name"]
print("logged in as", who)

MODEL_CARD = """---
base_model: Qwen/Qwen2.5-3B-Instruct
library_name: transformers
license: apache-2.0
tags: [sft, reasoning, math, llama-factory, course-project]
---
# Qwen2.5-3B-Instruct SFT ({run})

Full-parameter SFT of Qwen2.5-3B-Instruct on a 15K-sample subset of AceReason-1.1-SFT ({run} selection) with LLaMA-Factory
(DeepSpeed ZeRO-3, bf16, FlashAttention-2, Liger kernel, lr 5e-6, cosine, 3 epochs, global batch 8, cutoff 16,384 tokens).
Course project (Virginia Tech, Fall 2026). Dataset: {ds_repo}. Training config and environment freeze are in this repo
(`config_used.yaml`, `train_env_freeze.txt`). Evaluation: temperature 0.6, top-p 0.95, 8 samples, max 32,768 tokens,
system prompt "Please reason step by step, and put your final answer within \\boxed{{}}."
"""

DATA_CARD = """---
license: cc-by-4.0
task_categories: [text-generation]
tags: [reasoning, math, sft, acereason]
size_categories: [10K<n<100K]
---
# acereason-{run}

15,000 training examples selected from the 100K AceReason-1.1-SFT subset `redsgnaoh/acereason11_100k`
(LLaMA-Factory alpaca format: instruction / input / output / system). Selection method: {method}.
`manifest.json` lists the original row ids, the seed and the filter counts; `pool_stats.json` describes the source pool.
Source data: NVIDIA AceReason-1.1-SFT (responses generated by DeepSeek-R1); see the original dataset card for its license.
"""
METHOD = {
    "random15k": "uniform random sample of the whole pool with seed 20261015 (the required baseline, unfiltered)",
    "advanced15k": "math-only (`extra_info.category == math`), exact-duplicate prompts removed, complete conversations that fit "
                   "16,384 tokens under the Qwen chat template, stratified by source x total-token band (<=4K, 4-8K, 8-16K) "
                   "with proportional quotas, seed 20261015",
}

for run in a.datasets:
    repo = f"{a.namespace}/acereason-{run}"
    print("dataset ->", repo)
    if a.dry_run: continue
    create_repo(repo, repo_type="dataset", private=a.private, exist_ok=True)
    upload_file(path_or_fileobj=f"{P}/data/selections/{run}.json", path_in_repo=f"data/{run}.json", repo_id=repo, repo_type="dataset")
    upload_file(path_or_fileobj=f"{P}/data/selections/{run}_manifest.json", path_in_repo="manifest.json", repo_id=repo, repo_type="dataset")
    upload_file(path_or_fileobj=f"{P}/data/selections/pool_stats.json", path_in_repo="pool_stats.json", repo_id=repo, repo_type="dataset")
    upload_file(path_or_fileobj=DATA_CARD.format(run=run, method=METHOD.get(run, run)).encode(), path_in_repo="README.md", repo_id=repo, repo_type="dataset")
    print("  done:", f"https://huggingface.co/datasets/{repo}")

for run in a.models:
    repo = f"{a.namespace}/Qwen2.5-3B-Instruct-SFT-{run}"
    src = f"{P}/models/{run}"
    needed = ["config.json", "tokenizer_config.json", "tokenizer.json", "model.safetensors.index.json"]
    missing = [f for f in needed if not os.path.isfile(os.path.join(src, f))]
    if missing:
        print("  MISSING in", src, missing); sys.exit(2)
    print("model ->", repo, "from", src)
    if a.dry_run: continue
    create_repo(repo, repo_type="model", private=a.private, exist_ok=True)
    upload_folder(folder_path=src, repo_id=repo, repo_type="model",
                  ignore_patterns=["checkpoint-*", "*.pt", "global_step*", "trainer_log.jsonl", "training_args.bin", "wandb/*", "*.png"])
    upload_file(path_or_fileobj=MODEL_CARD.format(run=run, ds_repo=f"{a.namespace}/acereason-{run}").encode(), path_in_repo="README.md", repo_id=repo, repo_type="model")
    print("  done:", f"https://huggingface.co/{repo}")
