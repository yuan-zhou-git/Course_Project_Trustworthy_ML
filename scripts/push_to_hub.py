#!/usr/bin/env python
"""Push the fine-tuned models and both 15K datasets to the Hugging Face Hub (public by default).

Needs a write token already stored by `hf auth login` (never passed on the command line).
Usage (login node is fine: network + file IO only):
  python push_to_hub.py --models advanced15k_ep5 random15k --datasets random15k advanced15k [--private] [--dry-run]

Model repos:   <namespace>/Qwen2.5-3B-Instruct-SFT-<run>
Dataset repos: <namespace>/acereason-<dataset>   (the 15K json in LLaMA-Factory alpaca format + its manifest)
Existing repos are switched to the requested visibility; dataset files already on the Hub are not uploaded again.
"""
import argparse, glob, os, shutil, sys
from huggingface_hub import HfApi, create_repo, upload_folder, upload_file

P = "/projects/ai_wireless_hu_lab/yuanzhou/reasoning_sft"
GITHUB = "https://github.com/yuan-zhou-git/Course_Project_Trustworthy_ML"
ap = argparse.ArgumentParser()
ap.add_argument("--namespace", default="yuan-zhou-hf")
ap.add_argument("--models", nargs="*", default=[])
ap.add_argument("--datasets", nargs="*", default=[])
ap.add_argument("--private", action="store_true")
ap.add_argument("--dry-run", action="store_true")
a = ap.parse_args()
api = HfApi()
print("logged in as", api.whoami()["name"])

COURSE = f"""## Course project

Group 2, Trustworthy Machine Learning (Fall 2026), Virginia Tech: **Hanze Li, Sijie Chen, Yuan Zhou, Yiming Liang**.
Assignment: [reds-lab/Project-Reasoning-SFT-LLM](https://github.com/reds-lab/Project-Reasoning-SFT-LLM).
Code, configs, evaluation logs and report: [{GITHUB.split('/', 3)[3]}]({GITHUB}).
"""

EVAL = ("Evaluation (course harness, vLLM): temperature 0.6, top-p 0.95, 8 samples per question, max 32,768 tokens, seed 0, "
        "system prompt \"Please reason step by step, and put your final answer within \\boxed{}.\" Macro = mean over CN-Math 2024, "
        "Kaoyan, AMC, Minerva, OlympiadBench and GPQA (the locally available leaderboard benchmarks).")

# per-benchmark pass@8 / pass@1 (reports/five_models/results.json)
RESULTS = {
    "advanced15k_ep5": [("AIME24", ".233 / .075"), ("MATH-500", ".878 / .659"), ("CN-Math 2024", ".333 / .104"),
                        ("Kaoyan", ".678 / .298"), ("AMC", ".775 / .381"), ("Minerva", ".456 / .273"),
                        ("OlympiadBench", ".538 / .301"), ("GPQA", ".758 / .258"), ("**macro**", "**.590 / .269**")],
    "random15k": [("AIME24", ".333 / .071"), ("MATH-500", ".884 / .647"), ("CN-Math 2024", ".333 / .079"),
                  ("Kaoyan", ".653 / .292"), ("AMC", ".575 / .344"), ("Minerva", ".471 / .255"),
                  ("OlympiadBench", ".526 / .278"), ("GPQA", ".737 / .230"), ("**macro**", "**.549 / .246**")],
}
MODELS = {
    "advanced15k_ep5": dict(
        title="final model: selected 15K, 5 epochs", dataset="advanced15k",
        recipe="5 epochs (9,375 steps): epochs 1-3 at lr 5e-6 with a cosine schedule, then epochs 4-5 resumed from the epoch-3 "
               "weights, optimizer and scheduler on a 5-epoch cosine (lr 1.7e-6 to 0)"),
    "random15k": dict(
        title="random 15K baseline, 3 epochs", dataset="random15k",
        recipe="3 epochs (5,625 steps), lr 5e-6, cosine schedule"),
}

MODEL_CARD = """---
base_model: Qwen/Qwen2.5-3B-Instruct
library_name: transformers
license: other
license_name: qwen-research
license_link: https://huggingface.co/Qwen/Qwen2.5-3B-Instruct/blob/main/LICENSE
datasets: [{ns}/acereason-{dataset}]
tags: [sft, reasoning, math, llama-factory, course-project]
---
# Qwen2.5-3B-Instruct SFT ({title})

Full-parameter supervised fine-tuning of [Qwen/Qwen2.5-3B-Instruct](https://huggingface.co/Qwen/Qwen2.5-3B-Instruct) on
[{ns}/acereason-{dataset}](https://huggingface.co/datasets/{ns}/acereason-{dataset}), a 15K subset of AceReason-1.1-SFT.
Training: LLaMA-Factory, DeepSpeed ZeRO-3, bf16, FlashAttention-2, Liger kernel, AdamW, warmup 0, global batch 8, cutoff
16,384 tokens, response-only loss; {recipe}. `config_used.yaml`, `trainer_state.json` and `train_env_freeze.txt` in this repo
record the run.

## Results (pass@8 / pass@1)

| benchmark | score |
|---|---|
{rows}

{eval}

{course}
## License

A derivative of Qwen2.5-3B-Instruct, distributed under the same **Qwen Research License** (`LICENSE`, copied from the base
model). Training data: NVIDIA AceReason-1.1-SFT (responses generated by DeepSeek-R1); see its dataset card for its terms.
"""

DATA_CARD = """---
license: cc-by-4.0
task_categories: [text-generation]
tags: [reasoning, math, sft, acereason, course-project]
size_categories: [10K<n<100K]
---
# acereason-{run}

15,000 training examples selected from the 100K AceReason-1.1-SFT subset `redsgnaoh/acereason11_100k`
(LLaMA-Factory alpaca format: instruction / input / output / system). Selection method: {method}.
`manifest.json` lists the original row ids, the seed and the filter counts; `pool_stats.json` describes the source pool.
{used_by}

{course}
Source data: NVIDIA AceReason-1.1-SFT (responses generated by DeepSeek-R1); see the original dataset card for its license.
"""
METHOD = {
    "random15k": "uniform random sample of the whole pool with seed 20261015 (the required baseline, unfiltered)",
    "advanced15k": "math-only (`extra_info.category == math`), exact-duplicate prompts removed, complete conversations that fit "
                   "16,384 tokens under the Qwen chat template, stratified by source x total-token band (<=4K, 4-8K, 8-16K) "
                   "with proportional quotas, seed 20261015",
}
USED_BY = {
    "random15k": "Used to train the random baseline `{ns}/Qwen2.5-3B-Instruct-SFT-random15k`.",
    "advanced15k": "Used to train the final model `{ns}/Qwen2.5-3B-Instruct-SFT-advanced15k_ep5` (5 epochs).",
}

def set_visibility(repo, repo_type):
    api.update_repo_settings(repo_id=repo, repo_type=repo_type, private=a.private)
    print("  visibility:", "private" if a.private else "public")

for run in a.datasets:
    repo = f"{a.namespace}/acereason-{run}"
    print("dataset ->", repo)
    if a.dry_run: continue
    create_repo(repo, repo_type="dataset", private=a.private, exist_ok=True)
    for src, dst in [(f"{P}/data/selections/{run}.json", f"data/{run}.json"),
                     (f"{P}/data/selections/{run}_manifest.json", "manifest.json"),
                     (f"{P}/data/selections/pool_stats.json", "pool_stats.json")]:
        if api.file_exists(repo, dst, repo_type="dataset"):
            print("  already on the Hub:", dst)
        else:
            upload_file(path_or_fileobj=src, path_in_repo=dst, repo_id=repo, repo_type="dataset"); print("  uploaded:", dst)
    card = DATA_CARD.format(run=run, method=METHOD.get(run, run), used_by=USED_BY.get(run, "").format(ns=a.namespace), course=COURSE)
    upload_file(path_or_fileobj=card.encode(), path_in_repo="README.md", repo_id=repo, repo_type="dataset")
    set_visibility(repo, "dataset")
    print("  done:", f"https://huggingface.co/datasets/{repo}")

for run in a.models:
    info = MODELS[run]
    repo = f"{a.namespace}/Qwen2.5-3B-Instruct-SFT-{run}"
    src = f"{P}/models/{run}"
    needed = ["config.json", "tokenizer_config.json", "tokenizer.json", "model.safetensors.index.json", "chat_template.jinja"]
    missing = [f for f in needed if not os.path.isfile(os.path.join(src, f))]
    if missing:
        print("  MISSING in", src, missing); sys.exit(2)
    print("model ->", repo, "from", src)
    lic = glob.glob(f"{P}/hf_cache/hub/models--Qwen--Qwen2.5-3B-Instruct/snapshots/*/LICENSE")
    if lic and not os.path.isfile(os.path.join(src, "LICENSE")):
        shutil.copyfile(lic[0], os.path.join(src, "LICENSE")); print("  copied upstream LICENSE")
    card = MODEL_CARD.format(ns=a.namespace, title=info["title"], dataset=info["dataset"], recipe=info["recipe"],
                             rows="\n".join(f"| {b} | {s} |" for b, s in RESULTS[run]), eval=EVAL, course=COURSE)
    if a.dry_run:
        print(card); continue
    create_repo(repo, repo_type="model", private=a.private, exist_ok=True)
    upload_folder(folder_path=src, repo_id=repo, repo_type="model",
                  ignore_patterns=["checkpoint-*", "*.pt", "global_step*", "trainer_log.jsonl", "training_args.bin", "wandb/*",
                                   "*.png", ".keep", "README.md"])
    upload_file(path_or_fileobj=card.encode(), path_in_repo="README.md", repo_id=repo, repo_type="model")
    set_visibility(repo, "model")
    print("  done:", f"https://huggingface.co/{repo}")
